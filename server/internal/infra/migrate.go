package infra

import (
	"context"
	"database/sql"
	"embed"
	"fmt"
	"io/fs"

	"github.com/pressly/goose/v3"
	"gorm.io/gorm"
)

// baselineVersion 是旧数据库可被接管的最低迁移版本。
const baselineVersion int64 = 202611010001

// migrationFiles 内嵌生产数据库的 Goose 迁移文件。
//
//go:embed migrations/*.sql
var migrationFiles embed.FS

// Migrate 接管兼容的旧库并执行全部待应用的 PostgreSQL 迁移。
func Migrate(ctx context.Context, db *gorm.DB) error {
	if db == nil {
		return fmt.Errorf("migrate database: database is not initialized")
	}
	sqlDB, err := db.DB()
	if err != nil {
		return fmt.Errorf("migrate database: get sql database: %w", err)
	}
	if err := adoptBaseline(ctx, sqlDB); err != nil {
		return err
	}

	migrations, err := fs.Sub(migrationFiles, "migrations")
	if err != nil {
		return fmt.Errorf("migrate database: open migrations: %w", err)
	}
	provider, err := goose.NewProvider(goose.DialectPostgres, sqlDB, migrations)
	if err != nil {
		return fmt.Errorf("migrate database: create goose provider: %w", err)
	}
	if _, err := provider.Up(ctx); err != nil {
		return fmt.Errorf("migrate database: apply migrations: %w", err)
	}
	version, err := provider.GetDBVersion(ctx)
	if err != nil {
		return fmt.Errorf("migrate database: read version: %w", err)
	}
	if version < baselineVersion {
		return fmt.Errorf("migrate database: version %d is below baseline %d", version, baselineVersion)
	}
	return nil
}

// adoptBaseline 为具备完整旧表结构且无迁移记录的数据库登记基线版本。
func adoptBaseline(ctx context.Context, db *sql.DB) error {
	var existingTables int
	if err := db.QueryRowContext(ctx, `
		SELECT
			(to_regclass('public.sys_users') IS NOT NULL)::int +
			(to_regclass('public.xy_accounts') IS NOT NULL)::int +
			(to_regclass('public.xy_agent_sessions') IS NOT NULL)::int`).Scan(&existingTables); err != nil {
		return fmt.Errorf("migrate database: inspect existing schema: %w", err)
	}
	if existingTables == 0 {
		return nil
	}
	if existingTables != 3 {
		return fmt.Errorf("migrate database: existing schema is incomplete (%d of 3 required tables found)", existingTables)
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("migrate database: begin baseline adoption: %w", err)
	}
	defer tx.Rollback()

	if _, err := tx.ExecContext(ctx, `
		CREATE TABLE IF NOT EXISTS goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)`); err != nil {
		return fmt.Errorf("migrate database: create version table: %w", err)
	}

	var currentVersion int64
	if err := tx.QueryRowContext(ctx, "SELECT COALESCE(max(version_id) FILTER (WHERE is_applied), 0) FROM goose_db_version").Scan(&currentVersion); err != nil {
		return fmt.Errorf("migrate database: inspect migration history: %w", err)
	}
	if currentVersion == 0 {
		if _, err := tx.ExecContext(ctx, "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)", baselineVersion); err != nil {
			return fmt.Errorf("migrate database: record baseline: %w", err)
		}
	} else if currentVersion < baselineVersion {
		return fmt.Errorf("migrate database: existing migration version %d is below baseline %d", currentVersion, baselineVersion)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("migrate database: commit baseline adoption: %w", err)
	}
	return nil
}
